export async function seedBossAndChallengeDomains(): Promise<void> {
  console.log(`Bắt đầu seed ${EXTENDED_DOMAINS.length} bí cảnh Boss Tuần & Thử Thách...`);
  let count = 0;

  for (const item of EXTENDED_DOMAINS) {
    const payload = {
      name: item.name,
      nameTranslations: item.nameTranslations,
      category: item.category,
      regionName: item.regionName,
      description: item.description,
      recommendedLevel: item.recommendedLevel ?? null,
      recommendedElements: item.recommendedElements,
      daysOfWeek: item.daysOfWeek,
      unlockRank: item.unlockRank ?? null,
      materials: item.materials ? JSON.parse(JSON.stringify(item.materials)) : null,
      imageUrl: item.imageUrl ?? "/local-genshin-assets/ui/domain.png",
      imageUrlOriginal: item.imageUrl ?? null,
      gameVersion: item.gameVersion ?? null,
    };

    await prisma.domain.upsert({
      where: { id: item.id },
      create: { id: item.id, ...payload },
      update: payload,
    });
    count++;
  }

  console.log(`✔ Đã seed thành công ${count} bí cảnh Boss Tuần & Thử Thách vào Database!`);
}

if (import.meta.url.endsWith(process.argv[1]) || process.argv[1]?.includes("seed-boss-challenge-domains")) {
  seedBossAndChallengeDomains()
    .catch((err) => {
      console.error("Lỗi seed boss & challenge domains:", err);
      process.exit(1);
    })
    .finally(() => prisma.$disconnect());
}
